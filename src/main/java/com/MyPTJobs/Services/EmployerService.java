    public Boolean checkByToken(String token){
        if ( token.isEmpty() ){
            return false;
        }
        Optional<Employer> employer = employerRepository.checkExistingByToken(token);
        if ( employer.isPresent() ){


            return checkBlockOrNot(employer.get());
        }
        return false;
    }


    public boolean checkBlockOrNot(Employer employer){
        long currentTimeMillis = System.currentTimeMillis();
        Timestamp currentTime = new Timestamp(currentTimeMillis);
        if ( (employer.getBlockDate() == null || currentTime.after(employer.getBlockDate())) && employer.getBlockPermanent() == 0 ){
            return true;
        }
        return false;
    }

    public boolean checkCompleteInformationOrNot(Employer employer){
        String completeness = employerRepository.checkEmployerCompleteness(employer.getId());
        if ( completeness.equals("complete") ){
            return true;
        }
        return false;
    }

