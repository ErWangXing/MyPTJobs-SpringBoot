    public List<Employer> requestKYBList(String filter) {
        CriteriaBuilder cb = entityManager.getCriteriaBuilder();
        CriteriaQuery<Employer> query = cb.createQuery(Employer.class);
        Root<Employer> root = query.from(Employer.class);
        List<Predicate> predicates = new ArrayList<>();
        // add conditions to the predicates list

        if (!filter.isEmpty()) {
            predicates.add(cb.like(root.get("companyName"), "%" + filter + "%"));
        }

        predicates.add(cb.equal(root.get("verification"), "Pending"));

        // combine the predicates using a logical operator (AND or OR)
        Predicate combinedPredicate = cb.and(predicates.toArray(new Predicate[0]));

        // use constructor expression to select specific attributes
        query.select(cb.construct(Employer.class, root.get("id"), root.get("companyName"), root.get("imageFile"), root.get("verificationDate")));

        query.where(combinedPredicate);

        List<Employer> results = entityManager.createQuery(query).getResultList();
        return results;
    }

